import type { WeeklySchedulePack } from "../types";
import * as fs from "fs";
import * as path from "path";

/**
 * Synchronizes the generated canonical weekly schedule to the website's
 * source of truth: `src/lib/facts/local-class-schedule.ts`.
 */
export function syncScheduleToWebsite(
  pack: WeeklySchedulePack,
  websiteRoot: string,
): { targetFile: string; currentJsonFile: string } {
  const targetTsFile = path.join(
    websiteRoot,
    "src/lib/facts/local-class-schedule.ts",
  );
  const currentJsonFile = path.join(
    websiteRoot,
    "src/schedule/data/current-schedule.json",
  );

  // Write canonical JSON backup
  fs.writeFileSync(currentJsonFile, JSON.stringify(pack, null, 2), "utf-8");

  // Format DAY_STATUS for studio 1
  const s1 = pack.studios.studio1;
  const s2 = pack.studios.studio2;

  const dayStatusEntries: string[] = [];
  for (const [wDay, dayOverview] of Object.entries(s1.days)) {
    const noteProp = dayOverview.noteVi
      ? `, noteVi: ${JSON.stringify(dayOverview.noteVi)}`
      : "";
    dayStatusEntries.push(
      `    ${wDay}: { state: "${dayOverview.state}", date: "${dayOverview.dateDisplayVi}"${noteProp} },`,
    );
  }

  // Teacher by day entries
  const s1TeacherEntries = Object.entries(s1.teacherPattern)
    .map(([d, t]) => `      ${d}: ${JSON.stringify(t)},`)
    .join("\n");
  const s2TeacherEntries = Object.entries(s2.teacherPattern)
    .map(([d, t]) => `      ${d}: ${JSON.stringify(t)},`)
    .join("\n");

  // Format rows for Studio 1
  const formatStudioRows = (rows: typeof s1.rows) => {
    return rows
      .map((row) => {
        const classEntries = Object.entries(row.classes)
          .map(([d, cell]) => {
            return `          ${d}: c(${JSON.stringify(cell.en)}, ${JSON.stringify(cell.vi)}),`;
          })
          .join("\n");
        return `      {
        slot: "${row.slot}",
        classes: {
${classEntries}
        },
      },`;
      })
      .join("\n");
  };

  const s1RowsFormatted = formatStudioRows(s1.rows);
  const s2RowsFormatted = formatStudioRows(s2.rows);

  const fileContent = `// SOURCE OF TRUTH — Hai Duong studio group-class schedule.
// AUTO-GENERATED BY YOG JIVAN WEEKLY SCHEDULE ENGINE
// Generated: ${pack.generatedAt}
// Week: ${pack.weekLabelVi}

export type StudioScheduleId = "studio1" | "studio2";

export const DAY_KEYS = ["mon", "tue", "wed", "thu", "fri", "sat"] as const;
export type DayKey = (typeof DAY_KEYS)[number];

export const DAY_LABELS_VI: Record<DayKey, string> = {
  mon: "Thứ 2",
  tue: "Thứ 3",
  wed: "Thứ 4",
  thu: "Thứ 5",
  fri: "Thứ 6",
  sat: "Thứ 7",
};

/** Evergreen recurring batch times (Mon–Sat, Sunday closed). */
export const BATCH_SLOTS: Record<StudioScheduleId, readonly string[]> = {
  studio1: ["05:15–06:15", "06:30–07:30", "15:00–16:00", "17:15–18:15", "20:00–21:00"],
  studio2: ["05:00–06:00", "07:00–08:00", "15:30–16:30", "17:30–18:30", "19:45–20:45"],
};

export type ClassName = { en: string; vi: string };
/** A day either runs classes, is a holiday, or is closed for another reason. */
export type DayState = "active" | "holiday" | "closed";
export type DayStatus = { state: DayState; date: string; noteVi?: string };
/** A cell is absent when the day is not active. */
export type SlotRow = { slot: string; classes: Partial<Record<DayKey, ClassName>> };

const c = (en: string, vi: string): ClassName => ({ en, vi });

/** Canonical weekly timetable for ${pack.weekLabelVi}. */
export const WEEKLY_TIMETABLE = {
  weekStart: "${pack.weekStart}",
  weekEnd: "${pack.weekEnd}",
  /** Last day this rotating data may be shown as "this week". */
  validThrough: "${pack.validThrough}",
  weekLabelVi: "${pack.weekLabelVi}",
  dayStatus: {
${dayStatusEntries.join("\n")}
  } as Record<DayKey, DayStatus>,
  teacherByDay: {
    studio1: {
${s1TeacherEntries}
    },
    studio2: {
${s2TeacherEntries}
    },
  } as Record<StudioScheduleId, Partial<Record<DayKey, string>>>,
  rows: {
    studio1: [
${s1RowsFormatted}
    ],
    studio2: [
${s2RowsFormatted}
    ],
  } as Record<StudioScheduleId, readonly SlotRow[]>,
} as const;

/**
 * True only while the dated weekly timetable is still the current week.
 * Once it expires the UI must show evergreen batch slots instead.
 */
export function isWeeklyTimetableCurrent(now: Date = new Date()): boolean {
  return now.getTime() <= new Date(WEEKLY_TIMETABLE.validThrough).getTime();
}

/** Days in the current dated week that are closed, for a visible notice. */
export function closedDaysThisWeek(): { day: DayKey; status: DayStatus }[] {
  return DAY_KEYS.map((day) => ({ day, status: WEEKLY_TIMETABLE.dayStatus[day] })).filter(
    (d) => d.status.state !== "active",
  );
}

export const SCHEDULE_NOTE_VI =
  "Chủ đề lớp và giáo viên phụ trách có thể thay đổi theo từng tuần. Khung giờ lớp bên dưới là các ca cố định hằng tuần.";

export const SCHEDULE_ZALO_CTA_VI = "Nhận lịch tuần mới trên Zalo";
`;

  fs.writeFileSync(targetTsFile, fileContent, "utf-8");
  return { targetFile: targetTsFile, currentJsonFile };
}
